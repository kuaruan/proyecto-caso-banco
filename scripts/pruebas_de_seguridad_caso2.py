def revisar_github_actions(repo_dir: Path):
    workflows_dir = repo_dir / ".github" / "workflows"
    workflows = list(workflows_dir.glob("*.yml")) + list(workflows_dir.glob("*.yaml")) if workflows_dir.exists() else []

    if not workflows:
        agregar_hallazgo(
            "CI/CD y GitHub",
            "GitHub Actions",
            "No se detectaron workflows de GitHub Actions.",
            "Informativo",
            ".github/workflows ausente o sin YAML.",
            "Si el pipeline se ejecuta en CI/CD, versionar workflows con permisos mínimos.",
        )
    else:
        for wf in workflows:
            rel = ruta_relativa(wf, repo_dir)
            texto = leer_texto_seguro(wf)

            if not re.search(r"(?m)^permissions\s*:", texto):
                agregar_hallazgo(
                    "CI/CD y GitHub",
                    "Permisos mínimos en workflow",
                    "No se detectó bloque permissions explícito.",
                    "Medio",
                    rel,
                    "Definir permissions explícitos para reducir privilegios del GITHUB_TOKEN.",
                    "Agregar permissions: contents: read, y ampliar solo si es necesario.",
                )
            else:
                agregar_hallazgo(
                    "CI/CD y GitHub",
                    "Permisos mínimos en workflow",
                    "Workflow contiene bloque permissions explícito.",
                    "OK",
                    rel,
                    "Verificar que los permisos sean los mínimos necesarios.",
                )

            if re.search(r"(?m)^\s*pull_request_target\s*:", texto):
                agregar_hallazgo(
                    "CI/CD y GitHub",
                    "Evento pull_request_target",
                    "El workflow usa pull_request_target, evento que requiere controles estrictos.",
                    "Alto",
                    rel,
                    "Evitar ejecutar código no confiable con permisos elevados.",
                    "Usar pull_request cuando sea suficiente o restringir ejecución y revisión manual.",
                )

            if re.search(r"(?i)echo\s+.*\$\{\{\s*secrets\.", texto):
                agregar_hallazgo(
                    "CI/CD y GitHub",
                    "Exposición de secrets en logs",
                    "Se observó un posible echo de secrets en el workflow.",
                    "Alto",
                    rel,
                    "Nunca imprimir secretos en logs de CI/CD.",
                    "Eliminar echo de secrets y usar variables solo en comandos que las requieran.",
                )

            acciones = re.findall(r"uses:\s*([^\s#]+)", texto)
            acciones_inestables = [a for a in acciones if re.search(r"@(main|master|latest)$", a)]
            if acciones_inestables:
                agregar_hallazgo(
                    "CI/CD y GitHub",
                    "Versionamiento de actions",
                    "Se detectaron actions referenciadas a main/master/latest.",
                    "Medio",
                    f"{rel} | {', '.join(acciones_inestables[:5])}",
                    "Fijar versiones estables de acciones para evitar cambios inesperados.",
                    "Usar tags versionados o SHA cuando el contexto lo requiera.",
                )


