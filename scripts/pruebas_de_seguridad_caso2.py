# Revisión de logs del pipeline
PATRON_LOGS = re.compile(r"(?i)(\.log$|logs?/|log_|_log)")
PATRONES_EVENTOS_LOG = {
    "CRITICAL": re.compile(r"(?i)critical|fatal|panic"),
    "ERROR": re.compile(r"(?i)error|exception|traceback"),
    "WARNING": re.compile(r"(?i)warning|warn"),
    "ACCESS_DENIED": re.compile(r"(?i)unauthorized|forbidden|access denied|permission denied|authentication failed|login failed"),
    "RETRY_FAILURE": re.compile(r"(?i)retry|timeout|connection refused|connection failed"),
}


def revisar_logs(repo_dir: Path):
    candidatos = []
    for p in repo_dir.rglob("*"):
        if p.is_file() and not any(part in CARPETAS_OMITIDAS for part in p.parts):
            rel = ruta_relativa(p, repo_dir)
            if PATRON_LOGS.search(rel) and es_archivo_texto(p):
                candidatos.append(p)

    if not candidatos:
        agregar_hallazgo(
            "Logs y monitoreo",
            "Disponibilidad de logs",
            "No se detectaron archivos de log versionados o carpeta logs.",
            "Informativo",
            "No hay logs locales en el repositorio.",
            "Documentar dónde se generan los logs del pipeline y cómo revisarlos.",
            "Configurar logging estructurado y evitar subir logs con datos sensibles.",
        )
        return

    for log in candidatos[:50]:
        rel = ruta_relativa(log, repo_dir)
        texto = leer_texto_seguro(log, max_bytes=1_000_000)
        conteo = {nombre: len(patron.findall(texto)) for nombre, patron in PATRONES_EVENTOS_LOG.items()}
        total_eventos = sum(conteo.values())
        if conteo["CRITICAL"] or conteo["ACCESS_DENIED"]:
            sev = "Alto"
        elif conteo["ERROR"]:
            sev = "Medio"
        elif total_eventos:
            sev = "Bajo"
        else:
            sev = "OK"
        agregar_hallazgo(
            "Logs y monitoreo",
            "Eventos relevantes en logs",
            f"Eventos detectados en log: {total_eventos}",
            sev,
            f"{rel} | {conteo}",
            "Revisar eventos críticos, accesos fallidos y errores recurrentes. Evitar versionar logs con datos sensibles.",
            "Centralizar logs y definir alertas para ERROR/CRITICAL/accesos fallidos.",
        )

revisar_logs(repo_dir)
print("Revisión de logs completada")

