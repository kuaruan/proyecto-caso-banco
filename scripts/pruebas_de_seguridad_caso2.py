def clonar_o_actualizar_repo(repo_url: str, destino: Path, branch=None):
    destino.parent.mkdir(parents=True, exist_ok=True)

    if (destino / ".git").exists():
        print(f"Repositorio ya existe en: {destino}")
        resultado = ejecutar_comando(["git", "pull"], cwd=destino, timeout=180)
        if not resultado["ok"]:
            print("No fue posible actualizar con git pull. Se continuará con la copia local existente.")
            print(resultado["stderr"][:500])
        return destino

    cmd = ["git", "clone"]
    if branch:
        cmd += ["--branch", branch]
    cmd += [repo_url, str(destino)]

    print("Clonando repositorio...")
    resultado = ejecutar_comando(cmd, timeout=300)
    if not resultado["ok"]:
        raise RuntimeError(
            "No fue posible clonar el repositorio. Revisa conexión, permisos o URL.\n"
            + resultado["stderr"][:1000]
        )
    return destino

