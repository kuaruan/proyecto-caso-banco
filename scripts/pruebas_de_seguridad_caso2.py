def normalizar_puerto(puerto):
    texto = str(puerto)
    # formatos típicos: "5432:5432", "127.0.0.1:5432:5432", {target: 5432, published: 5432}
    if isinstance(puerto, dict):
        publicado = str(puerto.get("published", ""))
        target = str(puerto.get("target", ""))
        host_ip = str(puerto.get("host_ip", ""))
        return host_ip, publicado, target, texto
    partes = texto.split(":")
    if len(partes) == 1:
        return "", partes[0].split("/")[0], partes[0].split("/")[0], texto
    if len(partes) == 2:
        return "0.0.0.0", partes[0], partes[1].split("/")[0], texto
    return partes[0], partes[-2], partes[-1].split("/")[0], texto


