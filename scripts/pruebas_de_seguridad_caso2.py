def ejecutar_comando(cmd, cwd=None, timeout=120):
    """Ejecuta un comando local sin exponer errores fatales al notebook."""
    try:
        inicio = time.perf_counter()
        proc = subprocess.run(
            cmd,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=timeout,
            shell=False,
        )
        return {
            "cmd": " ".join(cmd),
            "returncode": proc.returncode,
            "stdout": proc.stdout,
            "stderr": proc.stderr,
            "tiempo_s": round(time.perf_counter() - inicio, 3),
            "ok": proc.returncode == 0,
        }
    except FileNotFoundError:
        return {
            "cmd": " ".join(cmd),
            "returncode": None,
            "stdout": "",
            "stderr": f"Comando no disponible: {cmd[0]}",
            "tiempo_s": 0,
            "ok": False,
        }
    except subprocess.TimeoutExpired:
        return {
            "cmd": " ".join(cmd),
            "returncode": None,
            "stdout": "",
            "stderr": f"Timeout ejecutando: {' '.join(cmd)}",
            "tiempo_s": timeout,
            "ok": False,
        }


def es_archivo_texto(path: Path) -> bool:
    if path.suffix.lower() in EXTENSIONES_TEXTO:
        return True
    try:
        with open(path, "rb") as f:
            chunk = f.read(2048)
        return b"\0" not in chunk
    except Exception:
        return False


def leer_texto_seguro(path: Path, max_bytes=2_000_000) -> str:
    """Lee texto limitando tamaño para evitar cargar archivos gigantes."""
    try:
        if path.stat().st_size > max_bytes:
            return ""
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""


def archivos_revisables(repo_dir: Path):
    for path in repo_dir.rglob("*"):
        if not path.is_file():
            continue
        if any(part in CARPETAS_OMITIDAS for part in path.parts):
            continue
        if es_archivo_texto(path):
            yield path


def ruta_relativa(path: Path, repo_dir: Path) -> str:
    try:
        return str(path.relative_to(repo_dir)).replace("\\", "/")
    except ValueError:
        return str(path)


def redactar_valor(valor: str, visible_inicio=4, visible_fin=2) -> str:
    """Redacta valores potencialmente sensibles. No imprime secretos completos."""
    if valor is None:
        return ""
    valor = str(valor).strip()
    if len(valor) <= visible_inicio + visible_fin + 3:
        return "***"
    return valor[:visible_inicio] + "***" + valor[-visible_fin:]


